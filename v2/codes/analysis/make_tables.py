#!/usr/bin/env python3
"""Generate the revised paper's LaTeX tables from v2 results.

Every number in the revised manuscript flows through this script (single
source of truth). Output: v2/paper/Quantum_Optimizer_Benchmarking/tables/*.tex

Tables:
  tab_cv_main.tex        CV: 6 configs x 6 arms, mean+-std over 5 seeds
  tab_factorial.tex      RoBERTa 2x2 factorial cells + effect estimates
  tab_ngd.tex            genuine NGD vs AdamW cells (per dataset + pooled)
  tab_cost.tex           measured cost of genuine QI-family methods
  tab_tabular_mlp.tex    tabular MLP benchmark
  tab_hessian.tex        Hessian spectrum summary (lambda_max by arm)
"""

import json
import math
from collections import defaultdict
from pathlib import Path
from statistics import mean, stdev

BASE = Path(__file__).resolve().parents[2]
RUNS = BASE / "runs"
OUT = BASE / "paper" / "Quantum_Optimizer_Benchmarking" / "tables"
OUT.mkdir(exist_ok=True)

STATS = json.loads((RUNS / "stats_summary.json").read_text())


def load():
    rows = []
    for p in RUNS.glob("*/**/result.json"):
        if "smoke" in str(p):
            continue
        try:
            r = json.loads(p.read_text())
        except Exception:
            continue
        if r.get("tag") == "smoke":
            continue
        rows.append(r)
    return rows


ROWS = load()


def sel(domain, dataset, model, arm_pred):
    by_seed = {}
    for r in ROWS:
        if (r["domain"], r["dataset"], r.get("model")) != (domain, dataset, model):
            continue
        if arm_pred(r):
            by_seed[r["seed"]] = r
    return list(by_seed.values())


def ms(rs, key="test_accuracy", pct=True, digits=None):
    vals = [r[key] for r in rs if r.get(key) is not None and math.isfinite(r[key])]
    if not vals:
        return "--"
    f = 100 if pct else 1
    d = digits if digits is not None else (1 if pct else 2)
    m = mean(vals) * f
    s = (stdev(vals) if len(vals) > 1 else 0.0) * f
    mark = ""
    if any(r.get("collapsed") for r in rs):
        n_c = sum(1 for r in rs if r.get("collapsed"))
        mark = f"$^{{\\dagger {n_c}/{len(rs)}}}$"
    return f"{m:.{d}f}\\,$\\pm$\\,{s:.{d}f}{mark}"


def opt_is(name):
    return lambda r: r["optimizer"] == name


# ------------------------------------------------------------------ CV main
def cv_main():
    configs = [("Fashion-MNIST", "fashion_mnist", "SimpleCNN"),
               ("Fashion-MNIST", "fashion_mnist", "ResNet18"),
               ("CIFAR-10", "cifar10", "SimpleCNN"),
               ("CIFAR-10", "cifar10", "ResNet18"),
               ("CIFAR-100", "cifar100", "SimpleCNN"),
               ("CIFAR-100", "cifar100", "ResNet18")]
    arms = [("SGD", "sgd"), ("Adam", "adam"), ("AdamW", "adamw"),
            ("NGD", "ngd"), ("HP-QNG", "ctrl_qng_hp"), ("SPSA", "spsa")]
    L = [
        "% AUTO-GENERATED by analysis/make_tables.py -- do not edit by hand",
        "\\begin{table*}[t]\\centering\\small",
        "\\setlength{\\tabcolsep}{4pt}",
        "\\caption{CV benchmark, v2 clean rerun: test accuracy (\\%, mean $\\pm$ std over seeds \\{42,1337,2025,7,123\\}). "
        "NGD = diagonal-Fisher natural gradient (classical QNG analog); HP-QNG = the hyperparameter-control "
        "configuration formerly labelled ``QNG-inspired''; SPSA = genuine Spall SPSA. "
        "$\\dagger$\\,$k/n$: $k$ of $n$ runs collapsed (NaN loss, aborted after 3 epochs; scored at final state).}",
        "\\label{tab:cv_main}",
        "\\begin{tabular}{l" + "c" * len(arms) + "}",
        "\\toprule",
        "Configuration & " + " & ".join(a[0] for a in arms) + " \\\\",
        "\\midrule",
    ]
    for disp, ds, model in configs:
        cells = [ms(sel("cv", ds, model, opt_is(code))) for _, code in arms]
        L.append(f"{disp} / {model} & " + " & ".join(cells) + " \\\\")
    L += ["\\bottomrule", "\\end{tabular}", "\\end{table*}"]
    (OUT / "tab_cv_main.tex").write_text("\n".join(L))


# ------------------------------------------------------------- factorial
def cell_pred(lr, wd):
    def p(r):
        if r["optimizer"] == "adamw" and abs(r["lr"] - lr) < 1e-12 and \
           abs(r.get("opt_kwargs", {}).get("weight_decay", 0.01) - wd) < 1e-9:
            return True
        if r["optimizer"] == "ctrl_qng_hp" and abs(lr - 1e-5) < 1e-12 and wd == 0.05:
            return True
        return False
    return p


def factorial():
    """Transposed layout (datasets as columns) so the table fits the text width."""
    ds_names = [("SST-2", "sst2"), ("IMDb", "imdb"), ("AG News", "ag_news")]
    cells_rows = [
        ("$\\eta{=}2\\mathrm{e}{-5}$, $\\lambda{=}0.01$ (v1 baseline)", 2e-5, 0.01),
        ("$\\eta{=}2\\mathrm{e}{-5}$, $\\lambda{=}0.05$", 2e-5, 0.05),
        ("$\\eta{=}1\\mathrm{e}{-5}$, $\\lambda{=}0.01$", 1e-5, 0.01),
        ("$\\eta{=}1\\mathrm{e}{-5}$, $\\lambda{=}0.05$ (v1 ``QNG'')", 1e-5, 0.05),
    ]
    eff_rows = [("$\\eta$ effect", "lr"), ("$\\lambda$ effect", "wd"),
                ("interaction", "interaction")]

    def fmt_eff(e):
        stars = "*" if e["p"] < 0.05 else ""
        return (f"{e['mean']*100:+.2f}{stars} "
                f"{{\\scriptsize[{e['ci'][0]*100:+.2f},{e['ci'][1]*100:+.2f}]}}")

    L = [
        "% AUTO-GENERATED by analysis/make_tables.py",
        "\\begin{table}[t]\\centering\\small",
        "\\setlength{\\tabcolsep}{5pt}",
        "\\caption{RoBERTa $2\\times2$ factorial decomposition of the original ``QNG-inspired'' configuration. "
        "Upper block: cell means (test accuracy \\%, $\\pm$ std, $n{=}5$ seeds). "
        "Lower block: seed-paired effect estimates in accuracy points with bootstrap 95\\% CIs; "
        "* marks paired-$t$ $p<0.05$. Percentile-bootstrap intervals at $n{=}5$ are "
        "approximate and can be narrower than $t$-based intervals; significance "
        "statements follow the paired $t$-test.}",
        "\\label{tab:factorial}",
        "\\begin{tabular}{lccc}",
        "\\toprule",
        " & " + " & ".join(d for d, _ in ds_names) + " \\\\",
        "\\midrule",
    ]
    for label, lr, wd in cells_rows:
        vals = [ms(sel("nlp", ds, "roberta", cell_pred(lr, wd)), digits=2) for _, ds in ds_names]
        L.append(f"{label} & " + " & ".join(vals) + " \\\\")
    L.append("\\midrule")
    for label, key in eff_rows:
        vals = [fmt_eff(STATS["factorial"][ds][key]) for _, ds in ds_names]
        L.append(f"{label} & " + " & ".join(vals) + " \\\\")
    L += ["\\bottomrule", "\\end{tabular}", "\\end{table}"]
    (OUT / "tab_factorial.tex").write_text("\n".join(L))


# ------------------------------------------------------------------ NGD
def ngd_table():
    ds_names = [("SST-2", "sst2"), ("IMDb", "imdb"), ("AG News", "ag_news")]
    L = [
        "% AUTO-GENERATED by analysis/make_tables.py",
        "\\begin{table}[t]\\centering\\small",
        "\\caption{Genuine diagonal-Fisher NGD on RoBERTa vs the two anchor AdamW cells "
        "(test acc.\\ \\%, $n{=}5$). $\\Delta$: seed-paired mean difference (pt). "
        "Pooled rows: Wilcoxon signed-rank over all 15 seed-pairs.}",
        "\\label{tab:ngd}",
        "\\begin{tabular}{lccc}",
        "\\toprule",
        "Dataset & NGD & $\\Delta$ vs v1-QNG cell & $\\Delta$ vs baseline \\\\",
        "\\midrule",
    ]
    for disp, ds in ds_names:
        ngd = ms(sel("nlp", ds, "roberta", opt_is("ngd")), digits=2)
        e = STATS["ngd"][ds]
        def f(x):
            s = "*" if x["p_paired_t"] < 0.05 else ""
            return f"{x['mean_diff']*100:+.2f}{s}"
        L.append(f"{disp} & {ngd} & {f(e['vs_v1qng'])} & {f(e['vs_baseline'])} \\\\")
    pq = STATS["ngd"]["pooled_vs_v1qng"]
    pb = STATS["ngd"]["pooled_vs_baseline"]
    def pooled_cell(x):
        return (f"{x['mean_diff']*100:+.2f} "
                f"{{\\scriptsize[{x['ci'][0]*100:+.2f},{x['ci'][1]*100:+.2f}]}} "
                f"($p{{=}}{x['p_wilcoxon']:.3f}$)")
    L += ["\\midrule",
          f"Pooled (Wilcoxon) & -- & {pooled_cell(pq)} & {pooled_cell(pb)} \\\\",
          "\\bottomrule", "\\end{tabular}", "\\end{table}"]
    (OUT / "tab_ngd.tex").write_text("\n".join(L))


# ------------------------------------------------------------------ cost
def cost_table():
    def t(domain, ds, model, arm):
        rs = sel(domain, ds, model, opt_is(arm))
        return mean(r["training_time_seconds"] for r in rs) / 3600 if rs else None

    rows = [
        ("LSTM / SST-2", t("nlp", "sst2", "lstm", "qpso"), 1435 / 3600, "chance (49.1)"),
        ("LSTM / IMDb", t("nlp", "imdb", "lstm", "qpso"), 1139 / 3600, "chance (50.1)"),
        ("\\emph{LSTM / AG News}$^{\\ast}$", 38.0, 3718 / 3600, "\\emph{not run (projected)}"),
        ("SimpleCNN / Fashion", t("cv", "fashion_mnist", "SimpleCNN", "qpso"),
         t("cv", "fashion_mnist", "SimpleCNN", "adam"), "chance-level"),
        ("SimpleCNN / CIFAR-10", t("cv", "cifar10", "SimpleCNN", "qpso"),
         t("cv", "cifar10", "SimpleCNN", "adam"), "chance-level"),
    ]
    L = [
        "% AUTO-GENERATED by analysis/make_tables.py",
        "\\begin{table}[t]\\centering\\small",
        "\\caption{Measured and projected wall-clock cost of genuine QPSO (10 particles) against Adam "
        "on a single T4 GPU, with resulting accuracy. $^{\\ast}$The AG News row is a "
        "projection from the measured per-step cost ratio; the run was not executed and "
        "the row contributes to no accuracy statistic. This measured infeasibility "
        "motivates restricting genuine population methods to small models.}",
        "\\label{tab:qpso_cost}",
        "\\begin{tabular}{lccc}",
        "\\toprule",
        "Config & QPSO (h/run) & Adam (h/run) & QPSO outcome \\\\",
        "\\midrule",
    ]
    for name, tq, ta, note in rows:
        tq_s = f"{tq:.1f}" if tq else "--"
        ta_s = f"{ta:.2f}" if ta else "--"
        ratio = f" ({tq/ta:.0f}$\\times$)" if tq and ta else ""
        L.append(f"{name} & {tq_s}{ratio} & {ta_s} & {note} \\\\")
    L += ["\\bottomrule", "\\end{tabular}", "\\end{table}"]
    (OUT / "tab_qpso_cost.tex").write_text("\n".join(L))


